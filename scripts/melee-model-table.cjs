'use strict';
// Generates client-mods/melee/melee-models.js: the first-person frame of every JasprApocalypse melee weapon's 3D model
// (display transform, grip, trail end points, cutting side), read from the checked-in resource pack models, so the
// first-person motion can map its canonical sprite poses onto each model. Usage: node scripts/melee-model-table.cjs [--check]
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const items = require('../client-mods/melee/melee-items.js');
const { meleeSpecs } = require('../apocalypse-pack/arsenal-expansion.cjs');
const OUT = path.join(root, 'client-mods/melee/melee-models.js');
const accents = Object.fromEntries(meleeSpecs.map(s => [s[0], s[4]]));

function center(e) { return [0, 1, 2].map(i => (e.from[i] + e.to[i]) / 2); }
function frameOf(id) {
  const file = path.join(root, 'apocalypse-pack/assets/minecraft/models/item/apocalypse_' + id + '.json');
  const j = JSON.parse(fs.readFileSync(file, 'utf8')), d = j.display && j.display.firstperson_righthand;
  if (!d || !Array.isArray(j.elements) || !j.elements.length) throw Error(id + ': no first-person display or elements');
  if (j.elements.some(e => e.rotation)) throw Error(id + ': rotated elements are not supported by the frame table');
  const named = re => j.elements.filter(e => re.test(e.__comment || ''));
  const cls = items.APOCALYPSE[id];
  const gripEl = named(/^grip( wrap)?$/)[0] || named(/^handle$/)[0] || named(/^(pole|shaft|haft)$/)[0] || j.elements[0];
  const g = center(gripEl);
  // a long handle or pole is held near its lower end, where a grip wrap would be
  if (!/^grip/.test(gripEl.__comment || '')) g[1] = Math.max(gripEl.from[1], 0) + Math.min(7, Math.min(gripEl.to[1], 7) - Math.max(gripEl.from[1], 0)) / 2;
  let top = -Infinity;
  for (const e of j.elements) if (e.to[1] > top) top = e.to[1];
  const guard = named(/guard|socket/)[0];
  const start = guard ? guard.to[1] : g[1] + 4;
  const span = top - start;
  const edgeEls = named(/edge|cutting|hook|axe blade|blade tip|blade spine|flail head|weighted head/);
  let side = 0; for (const e of edgeEls) side += center(e)[0] - 8;
  // the trail follows the working end: the cutting head of axes and polearms, the blade's line otherwise
  let tipX = 8, tipY = top;
  if (/^(axe|greataxe|scythe|glaive|flail)$/.test(cls) && edgeEls.length) {
    const c = edgeEls.map(center); tipX = c.reduce((s, v) => s + v[0], 0) / c.length; tipY = Math.max(...edgeEls.map(e => e.to[1]));
  }
  return {
    r: d.rotation.slice(), t: d.translation.slice(), s: d.scale[0],
    grip: g.map(v => +v.toFixed(3)),
    base: [8, +(start + span * 0.35).toFixed(3), 8], tip: [+tipX.toFixed(3), +tipY.toFixed(3), 8],
    edge: side < -0.25 ? -1 : 1, accent: accents[id] || null, length: +(top - g[1]).toFixed(2)
  };
}
function build() {
  const table = {};
  for (const id of Object.keys(items.APOCALYPSE).sort()) table[id] = frameOf(id);
  const body = '/* Generated by scripts/melee-model-table.cjs from apocalypse-pack models: do not edit by hand. First-person frames of\n' +
    ' * the JasprApocalypse melee weapons\' 3D models: display r/t/s, grip, trail base/tip (model px), cutting side (edge). */\n' +
    'var JasprMeleeModelTable = ' + JSON.stringify(table).replace(/\},"/g, '},\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, '\n}') + ';\n' +
    "if (typeof module !== 'undefined' && module.exports) module.exports = JasprMeleeModelTable;\n";
  return body;
}
if (require.main === module) {
  const text = build();
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === text;
    console.log(same ? 'melee-models.js is up to date' : 'melee-models.js is STALE'); process.exitCode = same ? 0 : 1;
  } else { fs.writeFileSync(OUT, text); console.log('wrote', OUT, Object.keys(items.APOCALYPSE).length, 'models'); }
}
module.exports = { build, frameOf };
