'use strict';
// Own art for two supplies (owner, 2026-10-05): Sanitized Flesh looks like jerky ("it should have its own texture, and it should
// look like jerky"), and the Portal Gun gets a new model with a texture painted for it ("the texture looks really bad ... the model
// should be better"). Merges the files into an EPK: the jerky texture and model, cooked_beef.json (the same model plus one
// override, jaspr_skin >= 1 -> the jerky model; the client's NBT-skin stage answers that predicate), and the Portal Gun's model
// and texture. Every unrelated entry stays byte-identical and the merge is idempotent. Writes only the --out folder.
//   node scripts/build-guns-pack.cjs --epk <assets.epk> --out <folder>
// Rebuild order for the live archive: live EPK -> this script (it owns cooked_beef.json and the two jaspr_sanitized_flesh files;
// the Portal Gun files are the apocalypse pack's, regenerated by apocalypse-pack/portal-gun-art.cjs).
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto'), zlib = require('node:zlib');
const assert = require('node:assert/strict');
const {decode, fileEntry} = require('./merge-apocalypse-assets.cjs');
const {encode} = require('./png-codec.cjs');
const jerky = require('./supply-art/jerky.cjs');
const portal = require('../apocalypse-pack/portal-gun-art.cjs');

const json = v => Buffer.from(JSON.stringify(v, null, 2) + '\n');
const SKIN_PREDICATE = 'jaspr_skin';
const NAMES = {
  jerkyTexture: 'assets/minecraft/textures/items/jaspr_sanitized_flesh.png',
  jerkyModel: 'assets/minecraft/models/item/jaspr_sanitized_flesh.json',
  beefModel: 'assets/minecraft/models/item/cooked_beef.json',
  portalModel: 'assets/minecraft/models/item/apocalypse_portal_gun.json',
  portalTexture: 'assets/minecraft/textures/items/apocalypse_portal_gun.png'
};

/** The files of the pack. `beefBase` is the archive's own cooked_beef.json (parsed), so its other fields survive. */
function build(beefBase = {parent: 'item/generated', textures: {layer0: 'items/beef_cooked'}}) {
  const files = new Map();
  const px = jerky.pixels();
  files.set(NAMES.jerkyTexture, encode({w: 16, h: 16, rgba: Buffer.from(px.flatMap(c => c ? [c[0], c[1], c[2], 255] : [0, 0, 0, 0]))}));
  files.set(NAMES.jerkyModel, json({parent: 'item/generated', textures: {layer0: 'items/jaspr_sanitized_flesh'}}));
  const base = {...beefBase};
  delete base.overrides;
  files.set(NAMES.beefModel, json({...base, overrides: [{predicate: {[SKIN_PREDICATE]: 1}, model: 'item/jaspr_sanitized_flesh'}]}));
  const art = portal.build();
  files.set(NAMES.portalModel, json(art.model));
  files.set(NAMES.portalTexture, encode(art.texture));
  return files;
}

/** Emulates 1.12 ItemOverrideList: reversed order, first override whose predicates are all <= the item's values. */
function resolve(overrides, values, fallback) {
  for (let i = overrides.length - 1; i >= 0; i--) {
    const p = overrides[i].predicate;
    if (Object.entries(p).every(([k, v]) => Math.fround(values[k] === undefined ? -Infinity : values[k]) >= Math.fround(v))) return overrides[i].model;
  }
  return fallback;
}

function merge(input) {
  const parsed = decode(input), byName = new Map(parsed.entries.map(e => [e.name, e]));
  assert.ok(byName.has(NAMES.beefModel), 'EPK layout (assets/ prefix) changed: cooked_beef.json');
  assert.ok(byName.has(NAMES.portalModel), 'the Portal Gun model must already be in the archive');
  const files = build(JSON.parse(byName.get(NAMES.beefModel).value.toString('utf8')));
  const outputEntries = parsed.entries.map(e => files.has(e.name) ? {...e, value: files.get(e.name), raw: fileEntry(e.name, files.get(e.name))} : e);
  for (const [name, value] of files) if (!byName.has(name)) outputEntries.push({type: 'FILE', name, value, raw: fileEntry(name, value)});
  const header = Buffer.from(parsed.header);
  header.writeUInt32BE(outputEntries.length, parsed.countOffset);
  const payload = Buffer.concat([...outputEntries.map(e => e.raw), Buffer.from('END$')]);
  const compressed = parsed.compression === 'G' ? zlib.gzipSync(payload, {level: 9}) : parsed.compression === 'Z' ? zlib.deflateSync(payload, {level: 9}) : payload;
  const output = Buffer.concat([header, compressed, Buffer.from(':::YEE:>')]);
  const verified = decode(output), after = new Map(verified.entries.map(e => [e.name, e]));
  let unchanged = 0;
  for (const before of parsed.entries) if (!files.has(before.name)) { assert.deepEqual(after.get(before.name).raw, before.raw, before.name); unchanged++; }
  for (const [name, value] of files) assert.deepEqual(after.get(name).value, value, name);
  for (const [name, value] of files) {
    if (!name.endsWith('.json')) continue;
    const model = JSON.parse(value);
    for (const t of Object.values(model.textures || {})) assert.ok(after.has('assets/minecraft/textures/' + t + '.png'), name + ': missing texture ' + t);
    if (model.parent && !model.parent.startsWith('builtin/')) assert.ok(after.has('assets/minecraft/models/' + model.parent + '.json'), name + ': missing parent ' + model.parent);
    for (const o of model.overrides || []) assert.ok(after.has('assets/minecraft/models/' + o.model + '.json'), name + ': missing model ' + o.model);
  }
  return {output, unchanged, replaced: [...files.keys()].filter(n => byName.has(n)), added: [...files.keys()].filter(n => !byName.has(n)), files};
}

function main() {
  const arg = name => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : null; };
  const source = arg('--epk'), out = arg('--out');
  if (!source || !out) throw new Error('usage: --epk <assets.epk> --out <folder>');
  const input = fs.readFileSync(source);
  const merged = merge(input);
  // Selector proof: the skin predicate picks the jerky model for a skinned stack and nothing else changes.
  const beef = JSON.parse(merged.files.get(NAMES.beefModel));
  assert.equal(resolve(beef.overrides, {[SKIN_PREDICATE]: 0}, 'base'), 'base');
  assert.equal(resolve(beef.overrides, {[SKIN_PREDICATE]: 1}, 'base'), 'item/jaspr_sanitized_flesh');
  assert.equal(resolve(beef.overrides, {}, 'base'), 'base', 'an item with no skin keeps the vanilla model');
  const again = merge(merged.output);
  assert.ok(again.output.equals(merged.output), 'merge not idempotent');
  fs.mkdirSync(out, {recursive: true});
  fs.writeFileSync(path.join(out, 'assets.epk'), merged.output);
  const report = {source, sourceSha256: crypto.createHash('sha256').update(input).digest('hex'), sha256: crypto.createHash('sha256').update(merged.output).digest('hex'),
    beforeBytes: input.length, afterBytes: merged.output.length, unchangedEntries: merged.unchanged, replaced: merged.replaced, added: merged.added};
  fs.writeFileSync(path.join(out, 'asset-merge-report.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report, null, 2));
}
if (require.main === module) main();
module.exports = {build, merge, resolve, NAMES, SKIN_PREDICATE};
